describe('matchesAcceptedAnswer — tabla de regresión (gate F2)', () => {
  it.each(ROWS)('[%s] %j contra %j', (_source, given, accepted, options, _before, after) => {
    expect(matchesAcceptedAnswer(given, accepted, options)).toBe(after);
  });

  it('ningún acierto previo se vuelve incorrecto', () => {
    const regressions = ROWS.filter(
      ([, , , , before, after]) => before === 'match' && after === 'mismatch',
    );
    expect(regressions).toEqual([]);
  });

  it('los únicos cambios son los justificados por §5.5', () => {
    expect(ROWS.filter(([, , , , before, after]) => before !== after)).toHaveLength(15);
  });
});
